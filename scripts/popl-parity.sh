#!/bin/sh
# Single source of the POPL'10 relational-algebra parity table.
#
# The comparison target is Malecha, Morrisett, Shinnar and Wisnesky, "Toward a
# Verified Relational Database Management System" (POPL 2010): six primitives
# over finite *sets*, verified in Coq. Claiming parity per-operator invites the
# obvious reviewer question -- which of our theorems, and is it about the shipped
# executor or about a module nobody calls? -- so the answer is generated from
# `SQLeanite/ProofAxioms.lean`, which is the audited set, and every witness named
# here must appear there or this script fails.
#
# Modes:
#   --markdown   emit docs/PARITY.md to stdout
#   --json       emit the parity array for scripts/lean-manifest.sh
#   --check      verify every witness is audited and docs/PARITY.md is current
set -eu

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$root"
audit=$(mktemp)
python3 scripts/lean_sources.py SQLeanite/ProofAxioms.lean > "$audit"
target=docs/PARITY.md

rows=$(mktemp)
scratch=$(mktemp)
trap 'rm -f "$audit" "$rows" "$scratch"' EXIT

# primitive | status | witnesses (space separated, unqualified) | note
cat > "$rows" <<'ROWS'
selection|parity|CoreReadSemantics.execute_query_denotes|Three-valued `WHERE`; `UNKNOWN` contributes zero multiplicity rather than being folded into false.
projection|parity|CoreReadSemantics.execute_query_denotes|Projection sums source multiplicities over a deduplicated support domain.
permutation|parity|CoreReadSemantics.permuted_projection_denotes RelationalAlgebra.ofList_map_permute RelationalAlgebra.permute_eval RelationalAlgebra.permute_symm_eval|Reached from the live projection, not merely audited: reordering a `Core.Query`'s column list denotes `permute` of the unreordered projection, for both `DISTINCT` and non-`DISTINCT` queries.
union|parity|CoreReadSemantics.compound_denotes|`UNION ALL` and `UNION` are both covered; the distinct form is `distinct (unionAll ..)`.
difference|parity|CoreReadSemantics.compound_denotes|`EXCEPT` as `exceptAll` over deduplicated arms, which is SQLite's behaviour, and `INTERSECT` likewise.
cartesian product|parity, derived in the opposite direction|RelationalAlgebra.innerJoin_true_eval|POPL'10 derive join from product. We take inner join as primitive and prove product is its constant-true case, so parity holds with the derivation reversed. Stated rather than closed by manufacturing a primitive we do not have.
ROWS

witness_count=0
verify() {
  while IFS='|' read -r primitive status witnesses note; do
    [ -n "$primitive" ] || continue
    for witness in $witnesses; do
      if ! grep -q "SQLeanite\.${witness}\$" "$audit"; then
        printf 'popl-parity: witness not audited: SQLeanite.%s (%s)\n' \
          "$witness" "$primitive" >&2
        exit 1
      fi
      witness_count=$((witness_count + 1))
    done
  done < "$rows"
}

emit_markdown() {
  cat <<'HEAD'
# POPL'10 relational-algebra parity

Generated by `scripts/popl-parity.sh --markdown`. Do not edit by hand; every
witness below is checked against `SQLeanite/ProofAxioms.lean` on each run of
`scripts/live-path-check.sh`, so this table cannot drift from the audited set.

## The one framing statement: sets versus bags

POPL'10's relations are finite **sets** (`FSetInterface`): no duplicates, and no
NULL logic. SQLeanite's relations are **bags** -- `KRelation.Relation Row` is a
multiplicity function `Row -> Nat` -- evaluated under SQLite's three-valued
predicates, where `UNKNOWN` contributes zero multiplicity rather than being
treated as false.

That is a strictly harder target, and it is why the table below is not a
like-for-like comparison:

- duplicate semantics are explicit, so `UNION ALL` versus `UNION`, and `EXCEPT`
  over raw versus deduplicated arms, are different theorems here and
  indistinguishable there;
- every operator theorem has to preserve multiplicity, not merely membership;
- a rewrite that is sound over sets can be unsound over bags, which is why the
  live optimizer carries a *cost* certificate per selected rewrite and why one
  rewrite (`filterFusion`) has a proved negative result rather than a proof.

**State this as an improvement in target, never as parity.** "Parity" in the
table means "we have a theorem for the same primitive", not "we prove the same
thing about it".

## Per-primitive witnesses

HEAD
  printf '| POPL'"'"'10 primitive | our witness | status |\n'
  printf '|---|---|---|\n'
  while IFS='|' read -r primitive status witnesses note; do
    [ -n "$primitive" ] || continue
    formatted=""
    for witness in $witnesses; do
      if [ -z "$formatted" ]; then
        formatted="\`$witness\`"
      else
        formatted="$formatted<br>\`$witness\`"
      fi
    done
    printf '| %s | %s | %s |\n' "$primitive" "$formatted" "$status"
  done < "$rows"
  printf '\n### Notes\n\n'
  while IFS='|' read -r primitive status witnesses note; do
    [ -n "$primitive" ] || continue
    printf -- '- **%s** — %s\n' "$primitive" "$note"
  done < "$rows"
  cat <<'TAIL'

## Where the permutation claim was weakest, and what changed

`RelationalAlgebra.lean` is imported only by `CoreReadSemantics` and
`ProofAxioms`. So until `permuted_projection_denotes` existed, "we have their
permutation primitive" was a true statement about a standalone module and said
nothing about the shipped projection: an audit entry is not a live path. The
bridge is now stated over `Core.Query.projectedRows` -- the same projection
`execute_query_denotes` reports -- and two gates in `scripts/live-path-check.sh`
pin it there:

- `live projection permutation reaches the POPL permutation operator`
- `permutation bridge is stated over the executor's own projection`

## What is deliberately not claimed

- No claim that the *implementation* is comparable in scope: POPL'10 verify a
  query compiler over their own storage; the SQL surface here is frozen and
  bounded, and the storage format is SQLite's.
- No claim of general parser correctness. `parseCertified_agrees_parse` covers
  admitted ASTs, which is the same relative standard POPL'10 met against their
  PEG grammar.
- Aggregation, grouping, ordering and the join family are *additions* to their
  six primitives, not parity items, and are audited separately.
TAIL
}

emit_json() {
  printf '  "popl_parity": [\n'
  first=1
  while IFS='|' read -r primitive status witnesses note; do
    [ -n "$primitive" ] || continue
    if [ "$first" = 1 ]; then first=0; else printf ',\n'; fi
    printf '    {"primitive": "%s", "status": "%s", "witnesses": [' \
      "$primitive" "$status"
    inner=1
    for witness in $witnesses; do
      if [ "$inner" = 1 ]; then inner=0; else printf ', '; fi
      printf '"SQLeanite.%s"' "$witness"
    done
    printf ']}'
  done < "$rows"
  printf '\n  ]'
}

case ${1:---check} in
  --markdown)
    verify
    emit_markdown
    ;;
  --json)
    verify
    emit_json
    ;;
  --check)
    verify
    if [ ! -f "$target" ]; then
      printf 'popl-parity: %s is missing; run --markdown > %s\n' \
        "$target" "$target" >&2
      exit 1
    fi
    emit_markdown > "$scratch"
    if ! cmp -s "$scratch" "$target"; then
      printf 'popl-parity: %s is stale; regenerate with --markdown\n' \
        "$target" >&2
      diff -u "$target" "$scratch" >&2 || true
      exit 1
    fi
    printf 'popl parity table is current: %s primitives, %s audited witnesses\n' \
      "$(grep -c . "$rows")" "$(awk -F'|' '{n += split($3, parts, " ")} END {print n}' "$rows")"
    ;;
  *)
    printf 'usage: %s [--markdown|--json|--check]\n' "$0" >&2
    exit 2
    ;;
esac
